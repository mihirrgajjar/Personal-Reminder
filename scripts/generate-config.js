/**
 * Netlify Build Helper: Generate Production Frontend Configuration
 * 
 * Runs during Netlify build step to generate `assets/js/config.js` from
 * Netlify environment variables (SUPABASE_URL, SUPABASE_ANON_KEY, DEFAULT_TIMEZONE).
 * This ensures no credentials are hardcoded into Git repository source files.
 */

const fs = require('fs');
const path = require('path');

const supabaseUrl = process.env.SUPABASE_URL || 'https://your-project-ref.supabase.co';
const supabaseAnonKey = process.env.SUPABASE_ANON_KEY || 'your-anon-key-here';
const defaultTimezone = process.env.DEFAULT_TIMEZONE || 'Asia/Kolkata';

// Determine if running with real credentials or fallback
const isConfigured = !supabaseUrl.includes('your-project-ref') && !supabaseAnonKey.includes('your-anon-key');

const configContent = `/**
 * Personal Reminder - Production Runtime Configuration
 * Auto-generated by build script on ${new Date().toISOString()}
 */

window.APP_CONFIG = {
  SUPABASE_URL: '${supabaseUrl}',
  SUPABASE_ANON_KEY: '${supabaseAnonKey}',
  DEFAULT_TIMEZONE: '${defaultTimezone}',
  DEMO_MODE: ${!isConfigured}
};
`;

const targetPath = path.join(__dirname, '..', 'assets', 'js', 'config.js');

try {
  fs.writeFileSync(targetPath, configContent, 'utf8');
  console.log('[Build] Successfully generated assets/js/config.js');
  console.log(`[Build] Configured: ${isConfigured ? 'YES (Live Supabase Credentials)' : 'NO (Using Placeholder / Demo Mode)'}`);
} catch (err) {
  console.error('[Build Error] Failed to generate assets/js/config.js:', err.message);
  process.exit(1);
}
